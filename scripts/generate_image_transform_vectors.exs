urls =
  for {name, m, o, k} <- url_cases do
    item = media[m]
    opts = to_opts.(o) ++ if(k, do: [sign: true, key: k], else: [sign: false])
    %{"name" => name, "media" => m, "options" => o, "key" => k, "expected" => ImageTransform.url(item, opts)}
  end

