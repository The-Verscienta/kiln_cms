to_opts = fn o ->
  Enum.flat_map(o, fn
    {"width", v} -> [width: v]
    {"height", v} -> [height: v]
    {"aspect_ratio", v} -> [aspect_ratio: v]
    {"dpr", v} -> [dpr: v]
    {"fit", v} -> [fit: String.to_atom(v)]
    {"crop", v} -> [crop: String.to_atom(v)]
    {"format", v} -> [format: String.to_atom(v)]
    {"quality", v} -> [quality: v]
  end)
end

