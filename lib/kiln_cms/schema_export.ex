defmodule KilnCMS.SchemaExport do
  @moduledoc """
  Machine-readable schema for the headless `:json` delivery surface (#430).

  The last unshipped "one definition fans out" item from the v2 plan. A block
  definition already produces an embedded resource, a union member, an editor
  input and four serializers; this produces the artifact typed clients were
  missing — a JSON Schema (and a `.d.ts` on top of it, see
  `KilnCMS.SchemaExport.TypeScript`) describing exactly what
  `GET /api/content/:type/:slug?surface=json` returns.

  ## What it covers

    * every registered block, derived from its `Kiln.Block` declaration
      (`Kiln.Block.JsonSchema`), including plugin-contributed ones;
    * the `_type`-discriminated union over them, recursing into container
      blocks;
    * one document schema **per content type** — compiled types *and* the
      admin-defined dynamic ones, whose custom fields are rows rather than
      code, read at export time.

  That last part is why this is not a compile-time artifact and why the export
  is per-organization: two sites on one deployment have different dynamic types
  and different custom fields, so they have different schemas. `org_id` is
  therefore an argument everywhere here, defaulting to the sole org.

  ## Where it comes out

    * `mix kiln.export.schema` — a file or stdout, for a build step;
    * `GET /api/schema` — the live schema for the requesting site, so a client
      can fetch rather than vendor it.

  ## What it deliberately does not cover

  The **authoring** shape. The write API (#330) accepts the stored block tree,
  not the fired projection, and that surface is already described by the
  OpenAPI document at `/api/json/open_api`. Conflating the two would produce a
  schema that is wrong for both.
  """

  alias Kiln.Block.JsonSchema
  alias KilnCMS.CMS
  alias KilnCMS.CMS.ContentTypes
  alias KilnCMS.CMS.FieldDefinition
  alias KilnCMS.CMS.FieldTypes
  alias KilnCMS.CMS.ReverseFields

  @dialect "https://json-schema.org/draft/2020-12/schema"

  # See `with_actor/2`.
  @actor_override {__MODULE__, :actor_override}

  @doc """
  The actor the export reads a type's field definitions as (#1659): a
  `KilnCMS.SystemActor`, which `KilnCMS.CMS.FieldDefinition` admits for reads
  (see `docs/policy-matrix.md`, "The system actor"), rather than
  `authorize?: false`, which would skip every policy on it.
  """
  @spec system() :: KilnCMS.SystemActor.t() | nil
  def system do
    case Process.get(@actor_override, :unset) do
      :unset -> KilnCMS.SystemActor.new(:schema_export)
      actor -> actor
    end
  end

  @doc false
  # Test seam (#1659): run `fun` with `system/0` answering `actor` in this
  # process, so a test can take the grant away and prove the definitions read
  # fails CLOSED (raises) instead of exporting a type with no custom fields.
  # Process-local, and nothing on a request path calls it; code that could call
  # it could equally pass any actor it liked.
  @spec with_actor(term(), (-> result)) :: result when result: term()
  def with_actor(actor, fun) do
    previous = Process.get(@actor_override, :unset)
    Process.put(@actor_override, actor)

    try do
      fun.()
    after
      if previous == :unset,
        do: Process.delete(@actor_override),
        else: Process.put(@actor_override, previous)
    end
  end

  @typedoc """
  Options for `json_schema/1`.

    * `:org_id` — the site whose dynamic types and custom fields are described
      (default: the sole org);
    * `:types` — restrict to these content-type names (strings or atoms);
      unknown names raise, so a typo in a build script fails loudly;
    * `:base_url` — origin used for the document `$id`;
    * `:blocks_only` — skip content types entirely (no database read).
  """
  @type option ::
          {:org_id, Ash.UUID.t()}
          | {:types, [atom() | String.t()]}
          | {:base_url, String.t() | nil}
          | {:blocks_only, boolean()}

  @doc """
  The full JSON Schema document.

  Its root is a `oneOf` over the document schemas, so a fired `:json` artifact
  validates against the document as-is; individual pieces are addressable under
  `$defs` (`#/$defs/block`, `#/$defs/content_post`) for a consumer that wants
  one of them.
  """
  @spec json_schema([option()]) :: map()
  def json_schema(opts \\ []) do
    model = model(opts)

    content_defs =
      Map.new(model.content_types, fn ct -> {content_def_name(ct.type), content_schema(ct)} end)

    root_refs =
      Enum.map(model.content_types, &%{"$ref" => "#/$defs/#{content_def_name(&1.type)}"})

    %{
      "$schema" => @dialect,
      "title" => "KilnCMS delivery schema",
      "description" =>
        "The `:json` fired-artifact shape served by `GET /api/content/:type/:slug`. " <>
          "Generated by `mix kiln.export.schema` / `GET /api/schema`.",
      "x-kiln" => %{
        "surface" => "json",
        "artifact_format_version" => KilnCMS.Firing.Engine.format_version(),
        "content_types" => Enum.map(model.content_types, &to_string(&1.type)),
        # From the same filtered list `$defs` uses, not the raw registry scan:
        # `Blocks.modules/0` is duck-typed on `render/2`, so a module that
        # implements the renderer behaviour without `use Kiln.Block` is in the
        # list but has no DSL, and `Info.name/1` raises on it. Reading the raw
        # list here would 500 the endpoint on exactly the module `$defs` was
        # careful to skip.
        "blocks" => Enum.map(model.block_modules, &to_string(Kiln.Block.Info.name(&1)))
      },
      "$defs" => Map.merge(JsonSchema.defs(model.block_modules), content_defs)
    }
    |> put_id(Keyword.get(opts, :base_url))
    |> put_root(root_refs)
  end

  # What `json_schema/1` resolves before it formats anything: the block modules,
  # and the content types with their custom-field definitions loaded.
  defp model(opts) do
    org_id = Keyword.get_lazy(opts, :org_id, &KilnCMS.Accounts.default_org_id/0)
    types = Keyword.get(opts, :types)

    content_types =
      if Keyword.get(opts, :blocks_only, false) do
        # Still validate the names. `--blocks-only --type typo` would otherwise
        # write a silently-wrong artifact, and the endpoint would answer 200 to
        # `?blocks=only&type=nope` while documenting that unknown names are 400.
        if types, do: resolve_types(org_id, types)
        []
      else
        org_id |> resolve_types(types) |> Enum.map(&describe(&1, org_id))
      end

    %{
      org_id: org_id,
      block_modules: JsonSchema.block_modules(KilnCMS.Blocks.modules()),
      content_types: content_types
    }
  end

  @doc "The `$defs` key for a content type (`:post` → `content_post`)."
  @spec content_def_name(atom() | String.t()) :: String.t()
  def content_def_name(type), do: "content_" <> String.replace(to_string(type), "-", "_")

  # ── content types ───────────────────────────────────────────────────────────

  defp resolve_types(org_id, nil), do: ContentTypes.all() ++ ContentTypes.dynamic_all(org_id)

  defp resolve_types(org_id, names) do
    all = resolve_types(org_id, nil)
    index = Map.new(all, &{to_string(&1.type), &1})

    # Deduplicated, and that is correctness rather than tidiness: `content_defs`
    # is a map and collapses a repeat, but the root `oneOf` is a list and does
    # not — and `oneOf` means *exactly one*, so `?type=post,post` would publish
    # a document that rejects every post it describes. Deduping also caps the
    # per-name `field_definitions` read, which an unbounded `?type=` list would
    # otherwise multiply into one query per repetition on a public endpoint.
    wanted = names |> Enum.map(&to_string/1) |> Enum.uniq()

    case Enum.reject(wanted, &Map.has_key?(index, &1)) do
      [] ->
        # Preserve the caller's order, so `--type post,page` reads back that way.
        Enum.map(wanted, &Map.fetch!(index, &1))

      unknown ->
        raise ArgumentError,
              "unknown content type(s): #{Enum.join(unknown, ", ")}. " <>
                "Known: #{Enum.map_join(all, ", ", &to_string(&1.type))}"
    end
  end

  # Definitions are registry metadata for a type the caller already named, and
  # the export runs outside any actor's session (a mix task has none), so the
  # read runs as `system/0` under the export's own org — the same posture
  # firing takes in `KilnCMS.Firing.CustomFields`. It fails closed (#1659): a
  # refused read would filter to `[]` and publish a schema with every custom
  # field missing, which a typed client would then build against.
  defp describe(%{source: :dynamic, definition: definition} = ct, org_id) do
    ct
    |> Map.put(
      :field_definitions,
      CMS.field_definitions_for_definition!(definition.id,
        actor: system(),
        authorize_with: :error,
        tenant: org_id
      )
    )
    |> put_reverse(org_id)
  end

  defp describe(%{type: type} = ct, org_id) do
    ct
    |> Map.put(
      :field_definitions,
      CMS.field_definitions_for!(type, actor: system(), authorize_with: :error, tenant: org_id)
    )
    |> put_reverse(org_id)
  end

  # The reverse fields records of this type show (R4): the other side of
  # every reference that may point here and names it.
  defp put_reverse(ct, org_id),
    do: Map.put(ct, :reverse_fields, ReverseFields.for_type(ct.type, org_id))

  defp content_schema(ct) do
    ct
    |> base_content_schema()
    |> put_inherited_fields(ct)
    |> put_plain_fields(ct)
    |> put_portable_fields(ct)
    |> put_reverse_fields(Map.get(ct, :reverse_fields, []))
  end

  # Reverse fields (R4) are not part of the fired document — the connection
  # is the source's value — so they are an annotation, not a property: what a
  # consumer can ask `referencedBy(inverse:)` (GraphQL) for, and which
  # reference field on which source type each one mirrors.
  defp put_reverse_fields(schema, []), do: schema

  defp put_reverse_fields(schema, reverse_fields) do
    Map.put(
      schema,
      "x-kiln-reverse-fields",
      Enum.map(reverse_fields, fn reverse ->
        %{
          "name" => reverse.name,
          "label" => reverse.label,
          "field" => reverse.field,
          "source_type" => reverse.source_type
        }
      end)
    )
  end

  # Field-level localization (#1327): a type that can inherit a value along
  # the locale fallback chain fires an `inherited_fields` key naming what it
  # filled. Optional — it is present only when something was inherited — and
  # declared only on such a type, so every other type's schema is unchanged.
  defp put_inherited_fields(schema, ct) do
    if KilnCMS.I18n.FieldLocalization.inherits?(ct.resource, ct.field_definitions) do
      put_in(schema, ["properties", "inherited_fields"], %{
        "type" => "object",
        "description" =>
          "Which `:fallback` fields this variant left empty and inherited along the " <>
            "site's locale fallback chain, and from which locale: `custom_fields` and " <>
            "`blocks` (by block `_id`) nest, a record attribute maps straight to a " <>
            "locale. Present only when something was inherited.",
        "additionalProperties" => true
      })
    else
      schema
    end
  end

  # `deliver_plain` `:text` fields fire a `custom_fields_plain` sibling of
  # `custom_fields` (`KilnCMS.CMS.PlainFields`): one key per flagged field,
  # the value with its markup stripped. **Closed**, unlike `custom_fields` —
  # it is projected from the current definitions on every fire, a
  # point-in-time read included. Not `required`: an artifact fired before
  # the flag was set lacks it until the re-fire the flip enqueues lands.
  # Declared only on a type that flags a field, so every other type's schema
  # is unchanged.
  defp put_plain_fields(schema, ct) do
    case KilnCMS.CMS.PlainFields.names(ct.field_definitions) do
      [] ->
        schema

      names ->
        put_in(schema, ["properties", "custom_fields_plain"], %{
          "type" => "object",
          "description" =>
            "Plain-text renditions of the `:text` custom fields marked `deliver_plain`: " <>
              "the stored value with its HTML tags removed, entities decoded and " <>
              "whitespace collapsed. `null` where the record holds no value.",
          "properties" => Map.new(names, &{&1, %{"type" => ["string", "null"]}}),
          "additionalProperties" => false
        })
    end
  end

  # `deliver_portable` rich `:text` fields fire a `custom_fields_portable`
  # sibling (`KilnCMS.CMS.PortableFields`), closed and optional for the
  # reasons above. Each value is the type a `:rich_text` block field has —
  # an array of the shared `#/$defs/portable_text_block`, by `$ref` — so the
  # `.d.ts` (and every other emitter) types a field's prose and a block's
  # body as one thing.
  defp put_portable_fields(schema, ct) do
    case KilnCMS.CMS.PortableFields.names(ct.field_definitions) do
      [] ->
        schema

      names ->
        put_in(schema, ["properties", "custom_fields_portable"], %{
          "type" => "object",
          "description" =>
            "Portable Text renditions of the rich `:text` custom fields marked " <>
              "`deliver_portable`: the stored HTML as the same block tree a `rich_text` " <>
              "block's `body` holds. `null` where the record holds no value.",
          "properties" => Map.new(names, &{&1, JsonSchema.type_schema(:rich_text)}),
          "additionalProperties" => false
        })
    end
  end

  defp base_content_schema(ct) do
    %{
      "type" => "object",
      "title" => document_title(ct.type),
      "description" => "A published `#{ct.label}` as fired to the `:json` surface.",
      "x-kiln-content-type" => to_string(ct.type),
      "x-kiln-content-type-source" => to_string(ct.source),
      "properties" => %{
        "id" => %{"type" => "string", "format" => "uuid"},
        "type" => %{"const" => to_string(ct.type)},
        "title" => %{"type" => ["string", "null"]},
        "slug" => %{"type" => ["string", "null"]},
        "locale" => %{"type" => ["string", "null"]},
        "custom_fields" => custom_fields_schema(ct.field_definitions),
        "blocks" => %{"type" => "array", "items" => JsonSchema.block_ref()}
      },
      "required" => ["blocks", "custom_fields", "id", "locale", "slug", "title", "type"],
      "additionalProperties" => false
    }
  end

  # **Open**, though firing's own path is closed. `Firing.CustomFields.resolve/3`
  # projects onto the current definitions with a `Map.take` — but only on its
  # `recompute?: true` branch. Point-in-time delivery fires
  # `custom_fields: :as_stored` and returns the stored map whole, and
  # `?as_of=` is served from the very route this schema describes. So a field
  # deleted last month still reaches a historical read, and a closed object
  # would make that legitimately-published document validate against nothing.
  #
  # Nothing is `required`, including definitions marked required. A definition
  # added after existing content was last saved has no stored value, and firing
  # does not invent one — so "required" describes the editor, not the payload.
  #
  # A private field (#2044) is not described at all: it is never in a
  # delivered payload (`KilnCMS.CMS.PrivateFields`), and this schema is public.
  defp custom_fields_schema(definitions) do
    definitions = Enum.reject(definitions, &(Map.get(&1, :private) == true))

    %{
      "type" => "object",
      "description" =>
        "Admin-defined custom fields (`KilnCMS.CMS.FieldDefinition`). Open: a " <>
          "point-in-time read (`?as_of=`) serves the values stored at that " <>
          "instant, which may include fields since removed from the registry.",
      "properties" => Map.new(definitions, &{&1.name, custom_field_schema(&1)}),
      "additionalProperties" => true
    }
  end

  defp custom_field_schema(definition) do
    definition.field_type
    |> base_custom_field_schema(definition)
    |> put_target_types(definition)
    |> put_target_rules(definition)
    |> put_inverse(definition)
    |> put_link_fields(definition)
    |> put_localization(Map.get(definition, :localization))
  end

  # A reference's link fields (R3): each connection's snapshot carries their
  # values under `"link"`, typed like any custom field and open like the
  # snapshot itself. `x-kiln-link-fields` names them in editor order. A
  # connection that holds no link value has no `"link"` key, so it is never
  # required.
  defp put_link_fields(schema, %{field_type: :reference} = definition) do
    case FieldDefinition.link_fields(definition) do
      [] ->
        schema

      links ->
        link = %{
          "type" => "object",
          "description" => "Data on this connection (the reference field's link fields).",
          "properties" => Map.new(links, &{&1.name, custom_field_schema(&1)}),
          "additionalProperties" => true
        }

        schema
        |> put_snapshot_link(link)
        |> Map.put("x-kiln-link-fields", Enum.map(links, & &1.name))
    end
  end

  defp put_link_fields(schema, _definition), do: schema

  defp put_snapshot_link(%{"items" => item} = schema, link),
    do: Map.put(schema, "items", put_in(item, ["properties", "link"], link))

  # A single reference's snapshot is spelled out once it carries link data,
  # so a consumer typing `link` keeps `id` and `type` too.
  defp put_snapshot_link(schema, link) do
    schema
    |> Map.merge(Map.delete(reference_item_schema(), "type"))
    |> put_in(["properties", "link"], link)
  end

  # The content types a `:reference` field may point at (R2), whichever option
  # names them — one `target_type` or several `target_types` — so a consumer
  # reads one key either way and can tell which types a value's `"type"` may
  # name. An annotation, not an `enum` on that `"type"`, for the reason
  # `:select` exports none: narrowing the list leaves stored values naming a
  # type it no longer holds.
  defp put_target_types(schema, %{field_type: :reference} = definition) do
    case FieldDefinition.reference_targets(definition) do
      [] -> schema
      types -> Map.put(schema, "x-kiln-target-types", types)
    end
  end

  defp put_target_types(schema, _definition), do: schema

  # A reference's target-side options: `max_sources` (R1b), how many records
  # may connect to one target through the field, and a non-default
  # `on_target_delete` (R5), what purging a target does to its connections.
  # Annotations for the reason the item bounds are: they govern writes and
  # purges, and tightening the cap leaves stored connections alone.
  defp put_target_rules(schema, %{field_type: :reference} = definition) do
    schema
    |> put_bound("x-kiln-max-sources", Map.get(definition, :max_sources))
    |> put_bound("x-kiln-on-target-delete", delete_rule(Map.get(definition, :on_target_delete)))
  end

  defp put_target_rules(schema, _definition), do: schema

  defp delete_rule(rule) when rule in [:clear, :restrict], do: to_string(rule)
  defp delete_rule(_keep), do: nil

  # What a reference's targets call it (R4): the reverse field each target
  # shows, by the name `referencedBy(inverse:)` takes.
  defp put_inverse(schema, %{field_type: :reference, inverse_name: name} = definition)
       when is_binary(name),
       do:
         Map.put(schema, "x-kiln-inverse", %{"name" => name, "label" => definition.inverse_label})

  defp put_inverse(schema, _definition), do: schema

  # Field-level localization (#1327), as `Kiln.Block.JsonSchema` annotates a
  # block field: absent for the default, `:localized`.
  defp put_localization(schema, mode) when mode in [:shared, :fallback],
    do: Map.put(schema, "x-kiln-localization", to_string(mode))

  defp put_localization(schema, _mode), do: schema

  defp base_custom_field_schema(:integer, _d), do: %{"type" => ["integer", "null"]}
  defp base_custom_field_schema(:float, _d), do: %{"type" => ["number", "null"]}
  defp base_custom_field_schema(:boolean, _d), do: %{"type" => ["boolean", "null"]}

  defp base_custom_field_schema(:date, _d),
    do: %{"type" => ["string", "null"], "format" => "date"}

  defp base_custom_field_schema(:datetime, _d),
    do: %{"type" => ["string", "null"], "format" => "date-time"}

  defp base_custom_field_schema(:url, _d), do: %{"type" => ["string", "null"], "format" => "uri"}

  # Deliberately **not** an `enum` of the definition's options, for two
  # independent reasons. It would be wrong: `ApplyCustomFields` keeps an
  # untouched key as-is and firing never re-coerces, so narrowing or renaming an
  # option leaves every already-published document carrying a value outside the
  # new list — and an `enum` alongside `["string", "null"]` also forbids the
  # `null` that same type admits. And it would disclose: the option list is
  # admin-authored editorial vocabulary, which this endpoint has no reason to
  # publish anonymously.
  #
  # A multiple select is a list of those strings, in the editor's order — the
  # same stance on `enum`, and doubly so with `allow_custom`.
  defp base_custom_field_schema(:select, %{multiple: true} = d) do
    %{
      "type" => ["array", "null"],
      "items" => %{"type" => "string"},
      "uniqueItems" => true,
      "description" => "The chosen terms, in the order the editor arranged them."
    }
    |> put_item_bounds(d)
  end

  defp base_custom_field_schema(:select, _d), do: %{"type" => ["string", "null"]}

  # The item shape is `Media.Snapshot`'s — the same one an `image` block's
  # `"media"` key carries, so one decoder reads both.
  defp base_custom_field_schema(:media, %{multiple: true} = d) do
    %{
      "type" => ["array", "null"],
      "items" => KilnCMS.Media.Snapshot.json_schema(),
      "description" => "Snapshots of the picked media items, in gallery order."
    }
    |> put_item_bounds(d)
  end

  defp base_custom_field_schema(:media, _d) do
    KilnCMS.Media.Snapshot.json_schema()
    |> Map.put("type", ["object", "null"])
    |> Map.put("description", "Snapshot of the picked media item.")
  end

  # A list of references: the snapshots in the editor's order. The item shape
  # is spelled out (and open, so a later addition such as link data is not a
  # breaking change for a validating consumer).
  defp base_custom_field_schema(:reference, %{multiple: true} = d) do
    %{
      "type" => ["array", "null"],
      "items" => reference_item_schema(),
      "description" =>
        "Write-time snapshots of the referenced records, in the order the editor arranged them."
    }
    |> put_item_bounds(d)
  end

  defp base_custom_field_schema(:reference, _d) do
    %{
      "type" => ["object", "null"],
      "description" => "Write-time snapshot of a referenced record."
    }
  end

  # A group: one object keyed by its sub-fields, or a list of them when it
  # holds repeating rows. **Closed**, unlike the custom-field map around it:
  # a write refuses any key no sub-field declares, and `SyncFieldValues`
  # moves or purges a key when its sub-field is renamed or deleted, so no
  # stored row carries one. Nothing is `required`, for the reason no custom
  # field is — a sub-field added later has no value in older rows.
  # `x-kiln-sub-fields` names them in editor order.
  defp base_custom_field_schema(:group, %{multiple: true} = d) do
    %{
      "type" => ["array", "null"],
      "items" => group_row_schema(d),
      "description" => "Rows of this group, in the order the editor arranged them."
    }
    |> put_item_bounds(d)
    |> put_sub_field_names(d)
  end

  defp base_custom_field_schema(:group, d) do
    d
    |> group_row_schema()
    |> Map.update!("type", &[&1, "null"])
    |> put_sub_field_names(d)
  end

  # A rich `:text` field (the default `format`) holds sanitized HTML; saying
  # so lets a client pick its renderer without guessing. A plain one is text.
  defp base_custom_field_schema(:text, d) do
    if Map.get(d, :format, :rich) == :rich,
      do: %{"type" => ["string", "null"], "contentMediaType" => "text/html"},
      else: %{"type" => ["string", "null"]}
  end

  defp base_custom_field_schema(:string, _d), do: %{"type" => ["string", "null"]}

  # Everything else is a `Kiln.FieldType` — a built-in (geolocation, computed,
  # the event pair) or a plugin's. Ask the module: it may declare its delivered
  # JSON shape outright, and otherwise we infer one from its editor widget.
  defp base_custom_field_schema(type, definition) do
    case FieldTypes.get(type) do
      nil -> %{}
      module -> field_type_schema(module, definition)
    end
  end

  defp group_row_schema(definition) do
    %{
      "type" => "object",
      "properties" =>
        Map.new(FieldDefinition.group_fields(definition), &{&1.name, custom_field_schema(&1)}),
      "additionalProperties" => false
    }
  end

  defp put_sub_field_names(schema, definition),
    do:
      Map.put(
        schema,
        "x-kiln-sub-fields",
        Enum.map(FieldDefinition.group_fields(definition), & &1.name)
      )

  defp reference_item_schema do
    %{
      "type" => "object",
      "properties" => %{
        "id" => %{"type" => "string", "format" => "uuid"},
        "type" => %{"type" => "string"},
        "slug" => %{"type" => ["string", "null"]},
        "title" => %{"type" => ["string", "null"]}
      },
      "required" => ["id", "type"],
      "additionalProperties" => true
    }
  end

  # `min_items` / `max_items` (a list field's bounds) as annotations, not as
  # JSON Schema's `minItems`/`maxItems` — for the reason `:select` exports no
  # `enum`: the bounds govern what a *write* accepts, and a value stored before
  # a bound was tightened (or served by `?as_of=`) may fall outside it, so as
  # assertions they would fail legitimately-published documents.
  defp put_item_bounds(schema, d) do
    schema
    |> put_bound("x-kiln-min-items", Map.get(d, :min_items))
    |> put_bound("x-kiln-max-items", Map.get(d, :max_items))
  end

  defp put_bound(schema, _key, nil), do: schema
  defp put_bound(schema, key, value), do: Map.put(schema, key, value)

  # `Code.ensure_loaded?` before every probe: `FieldTypes.get/1` returns a module
  # atom out of a compile-baked literal map and never loads it, so under
  # interactive mode (which is how `mix kiln.export.schema` runs) an untouched
  # field-type module answers `false` to `function_exported?` and silently
  # exports as a bare string instead of its real shape.
  defp field_type_schema(module, definition) do
    loaded? = Code.ensure_loaded?(module)

    cond do
      loaded? and function_exported?(module, :json_schema, 1) ->
        module.json_schema(definition)

      # Branch on the parts themselves, not on whether the callback exists:
      # `use Kiln.FieldType` defaults `input_parts/1` to `[]`, so every scalar
      # type exports the callback too and probing for it would type them all as
      # empty objects.
      loaded? and parts(module, definition) != [] ->
        composite_schema(module.input_parts(definition))

      true ->
        %{"type" => [input_json_type(module, loaded?), "null"]}
    end
  end

  @doc """
  `module`'s declared composite input parts for `definition`, or `[]` if it
  doesn't implement `c:Kiln.FieldType.input_parts/1`.

  Public for the same reason `html_input_json_type/1` is: so `mix
  kiln.plugins.doctor` (#937) can ask "is this composite, and what are its
  parts" the same way this module does, rather than reimplementing the guard.
  """
  @spec parts(module(), struct()) :: [Kiln.FieldType.input_part()]
  def parts(module, definition) do
    if function_exported?(module, :input_parts, 1), do: module.input_parts(definition), else: []
  end

  # No `required`: `input_part.required?` means "carries the *definition's*
  # required flag", which is an editor concern — the same reason nothing in
  # `custom_fields` is required at all.
  defp composite_schema(parts) do
    %{
      "type" => ["object", "null"],
      "properties" =>
        Map.new(parts, fn part ->
          {part.key, %{"type" => html_input_json_type(Map.get(part, :type, "text"))}}
        end)
    }
  end

  defp input_json_type(module, true) do
    if function_exported?(module, :input_type, 0),
      do: html_input_json_type(module.input_type()),
      else: "string"
  end

  defp input_json_type(_module, false), do: "string"

  @doc """
  The JSON type an HTML input type implies (`"number"` → `"number"`, etc).

  Public so `mix kiln.plugins.doctor` (#937) can compare a plugin field
  type's `cast/2` output against what its editor widget implies, rather than
  reimplementing this table.
  """
  @spec html_input_json_type(String.t()) :: String.t()
  def html_input_json_type("number"), do: "number"
  def html_input_json_type("range"), do: "number"
  def html_input_json_type("checkbox"), do: "boolean"
  def html_input_json_type(_), do: "string"

  # ── document assembly ───────────────────────────────────────────────────────

  defp put_id(document, nil), do: document

  # `String.trim_trailing`: `$id` is the base every relative `$ref` resolves
  # against, and `--base-url https://example.com/` would otherwise publish
  # `https://example.com//api/schema`.
  defp put_id(document, base_url),
    do: Map.put(document, "$id", String.trim_trailing(base_url, "/") <> "/api/schema")

  # A blocks-only export has no document to be `oneOf` — leaving an empty
  # `oneOf` in would produce a schema nothing can satisfy.
  defp put_root(document, []), do: document
  defp put_root(document, refs), do: Map.put(document, "oneOf", refs)

  defp document_title(type), do: JsonSchema.pascal(type) <> "Document"
end
