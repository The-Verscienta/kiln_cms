defmodule KilnCMS.Security.CrawlerSighting do
  @moduledoc """
  When the 404 guard first saw a search-engine claim from a client outside
  the engine's published list (#2852).

  `KilnCMS.CrawlerVerification.listing_overdue?/3` counts such a claim once
  the client is still outside a list fetched at least a day after this
  sighting. Kept per node, the sighting restarted on every deploy, restart
  and autoscale, so an install that rolled more often than daily never
  counted a spoofer at all. A row here is the same answer on every node and
  survives a deploy.

  This resource owns the **table**: its shape, its migration (generated by
  `mix ash.codegen`), its policies and its pruning. The request path does not
  go through an Ash action: `KilnCMS.Security.CrawlerSightingStore` records
  and reads a sighting with one `INSERT ... ON CONFLICT DO UPDATE ...
  RETURNING`, as `KilnCMS.Accounts.ThrottleStore` does for the throttle
  counters, and its moduledoc says why.

  ## What a row holds, and what it does not

    * `key_hash`: an HMAC-SHA256 of the counted client (an IPv4 address, or
      an IPv6 address's `/64`) under a key derived from `secret_key_base`
      (`KilnCMS.Keys.ClientDigest`, #3501). No address is ever written in the
      clear, nor as a plain hash a dump could be reversed from.
    * `engine`: which engine's list the client is outside (`"duckduckgo"`),
      a constant chosen by the code.
    * `first_seen_at`: the first sighting, by the **database's** clock, so
      every node agrees on it.
    * `expires_at`: when the sighting lapses unless asked about again, which
      moves it on. The prune below deletes every row past it; a lapsed row
      the prune has not reached yet is a new sighting, never an old one.

  Nothing here references a site, a user or a request: one row per client
  and engine for the whole instance, like `throttle_counters`.

  ## Authorization

  System-only. No person, admin included, reads or writes a row: `:read` is
  forbidden to everyone, and `:prune` admits only the system actor and the
  AshOban cron that runs it. Sightings are recorded by
  `CrawlerSightingStore` under no actor at all, on the request path of an
  anonymous client.
  """
  use Ash.Resource,
    domain: KilnCMS.Security,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    extensions: [AshOban]

  postgres do
    table "crawler_sightings"
    repo KilnCMS.Repo

    custom_indexes do
      # The prune's scan.
      index [:expires_at], name: "crawler_sightings_expires_at_index"
    end
  end

  oban do
    scheduled_actions do
      # Hourly: a sighting lives 48 hours past its last question, so an hour
      # more before it goes changes nothing it decides. Oban's cron runs it
      # once per cluster, not once per node.
      schedule :prune, "41 * * * *" do
        action :prune
        queue :default
        worker_module_name KilnCMS.Security.CrawlerSighting.Workers.Prune
      end
    end
  end

  actions do
    defaults [:read]

    # Deletes every lapsed sighting, in bounded batches (see
    # `CrawlerSightingStore.prune/0`). Returns how many went.
    action :prune, :integer do
      run fn _input, _context -> {:ok, KilnCMS.Security.CrawlerSightingStore.prune()} end
    end
  end

  policies do
    # The scheduled prune.
    bypass AshOban.Checks.AshObanInteraction do
      authorize_if always()
    end

    policy action(:prune) do
      authorize_if {KilnCMS.Checks.SystemActor, subsystem: :operator}
    end

    # Nobody reads a sighting. A row names no address, but "this hashed
    # client claimed to be a crawler from outside its list" is still an
    # oracle nobody needs.
    policy action_type(:read) do
      forbid_if always()
    end
  end

  attributes do
    attribute :key_hash, :binary do
      primary_key? true
      allow_nil? false
      public? false
    end

    attribute :engine, :string do
      primary_key? true
      allow_nil? false
      public? false
      constraints max_length: 32
    end

    attribute :first_seen_at, :utc_datetime_usec do
      allow_nil? false
      public? false
    end

    attribute :expires_at, :utc_datetime_usec do
      allow_nil? false
      public? false
    end
  end
end
