defmodule KilnCMS.SchemaExport.TypeScript do
  @moduledoc """
  `.d.ts` emitter over the exported JSON Schema (#430).

  The issue left this optional — "or leave it to json-schema-to-typescript
  downstream". It ships because the downstream tool is a Node dependency in a
  build that may not otherwise have one, and because generating from our own
  document is a dozen lines of formatting rather than a toolchain.

  It reads the **JSON Schema document** rather than the block registry, so the
  two emitters cannot disagree about what a field is: everything
  `Kiln.Block.JsonSchema` and `KilnCMS.SchemaExport` decide (nullability,
  enums, the recursive block union, closed custom-field maps) is already baked
  into the document by the time this sees it. The reading itself is
  `KilnCMS.SchemaExport.Walk`, shared with `KilnCMS.SchemaExport.Swift`; this
  module only spells the walked model as TypeScript.

  Anything the emitter cannot express — `format`, `minimum`, `default` — is
  dropped rather than approximated. A `.d.ts` that lies about a constraint is
  worse than one that is merely loose about it.
  """

  alias KilnCMS.SchemaExport.Walk

  @doc """
  Emit TypeScript declarations for a schema document from
  `KilnCMS.SchemaExport.json_schema/1`.
  """
  @spec emit(map()) :: String.t()
  def emit(document) do
    model = Walk.model(document)

    [
      header(model),
      section("Shared", declarations(model.shared)),
      section("Blocks", declarations(model.blocks)),
      section("Block union", [union_alias("KilnBlock", model.block_union)]),
      section("Documents", declarations(model.documents)),
      section("Document union", [document_union(model.document_union.members)])
    ]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n")
  end

  defp header(model) do
    """
    // Generated by `mix kiln.export.schema --format ts`. Do not edit.
    //
    // The `:json` fired-artifact shape served by
    // `GET /api/content/:type/:slug?surface=json`.
    //
    // Artifact format version: #{model.format_version || "unknown"}
    """
  end

  defp section(title, declarations) do
    case Enum.reject(declarations, &(&1 == "")) do
      [] ->
        ""

      declarations ->
        rule = String.duplicate("-", max(0, 60 - String.length(title)))
        "\n// -- #{title} #{rule}\n\n" <> Enum.join(declarations, "\n\n") <> "\n"
    end
  end

  defp declarations(decls), do: Enum.map(decls, &interface/1)

  # A document with no block union at all (a hand-assembled `$defs`, or a future
  # partial export) simply has no alias to emit.
  defp union_alias(_name, nil), do: ""

  defp union_alias(name, %{members: members}) do
    members = Enum.map_join(members, "\n  | ", &type_name(&1.def))
    "export type #{name} =\n  | #{members};"
  end

  defp document_union([]), do: ""

  defp document_union(members) do
    members = Enum.map_join(members, "\n  | ", &type_name(&1.def))
    "export type KilnDocument =\n  | #{members};"
  end

  defp interface(%{shape: {:object, fields, open?}} = decl) do
    body =
      Enum.map_join(fields, "\n", fn field ->
        "  #{property_key(field.key)}#{optional(field)}: #{annotation(field)}#{ts_type(field.type)};"
      end)

    extra = if open?, do: "\n  [k: string]: unknown;", else: ""

    "#{doc_comment(decl)}export interface #{type_name(decl.name)} {\n#{body}#{extra}\n}"
  end

  # A schema with no `properties` (a lone `const`, an open object) has no
  # interface to write — alias it to `unknown` rather than emitting `{}`, which
  # TypeScript treats as "anything but null".
  defp interface(%{shape: :opaque} = decl),
    do: "#{doc_comment(decl)}export type #{type_name(decl.name)} = unknown;"

  defp doc_comment(%{description: nil}), do: ""

  defp doc_comment(%{description: description}),
    do: "/** #{String.replace(description, "*/", "*\\/")} */\n"

  defp optional(%{required?: true}), do: ""
  defp optional(_field), do: "?"

  # ── type mapping ────────────────────────────────────────────────────────────

  defp ts_type({:ref, name}), do: type_name(name)
  defp ts_type({:union, members}), do: Enum.map_join(members, " | ", &ts_type/1)
  defp ts_type({:nullable, inner}), do: ts_type(inner) <> " | null"
  defp ts_type({:const, value}), do: literal(value)
  defp ts_type({:enum, values}), do: Enum.map_join(values, " | ", &literal/1)
  defp ts_type({:array, items}), do: "Array<" <> ts_type(items) <> ">"
  defp ts_type({:object, fields, _open?}), do: inline_object(fields)
  defp ts_type(:map), do: "Record<string, unknown>"
  defp ts_type(:integer), do: "number"
  defp ts_type(:number), do: "number"
  defp ts_type(:boolean), do: "boolean"
  defp ts_type(:string), do: "string"
  defp ts_type(:null), do: "null"
  defp ts_type(:unknown), do: "unknown"

  defp inline_object(fields) do
    body =
      Enum.map_join(fields, "; ", fn field ->
        "#{property_key(field.key)}#{optional(field)}: #{annotation(field)}#{ts_type(field.type)}"
      end)

    "{ " <> body <> " }"
  end

  # A `:reference` custom field's allowed target types (R2) ride along as an
  # inline comment ahead of its type. Not a literal union on the snapshot's
  # `type`: the JSON Schema states them as an annotation, not an `enum`, since
  # a stored value may name a type the field has since stopped allowing.
  defp annotation(%{target_types: [_ | _] = types}),
    do:
      "/* links to: #{types |> Enum.map_join(" | ", &literal/1) |> String.replace("*/", "*\\/")} */ "

  defp annotation(_field), do: ""

  defp literal(value) when is_binary(value), do: ~s(") <> escape(value) <> ~s(")
  defp literal(value), do: to_string(value)

  # Custom-field names and `:select` options are admin input with no charset
  # validation, so a backslash or a newline in one would otherwise emit a
  # `.d.ts` that silently changes meaning (`C:\reports` → `C:reports`) or does
  # not parse at all. Backslash first, or it would re-escape the escapes.
  defp escape(value) do
    value
    |> String.replace("\\", "\\\\")
    |> String.replace(~s("), ~s(\\"))
    |> String.replace("\n", "\\n")
    |> String.replace("\r", "\\r")
    |> String.replace("\t", "\\t")
  end

  # ── naming ──────────────────────────────────────────────────────────────────

  # `block_rich_text` → `RichTextBlock`, `content_post` → `PostDocument`,
  # `portable_text_block` → `PortableTextBlock`, `block` → `KilnBlock`.
  defp type_name("block"), do: "KilnBlock"

  defp type_name("block_" <> rest), do: pascal(rest) <> "Block"
  defp type_name("content_" <> rest), do: pascal(rest) <> "Document"
  defp type_name(name), do: pascal(name)

  defp pascal(name), do: Kiln.Block.JsonSchema.pascal(name)

  # A key that is not a plain identifier has to be quoted, or the declaration
  # will not parse. Custom-field names are admin input, so this is not
  # hypothetical.
  defp property_key(key) do
    if Regex.match?(~r/^[A-Za-z_$][A-Za-z0-9_$]*$/, key),
      do: key,
      else: ~s(") <> escape(key) <> ~s(")
  end
end
