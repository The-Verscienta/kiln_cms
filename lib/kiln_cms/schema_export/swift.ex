defmodule KilnCMS.SchemaExport.Swift do
  @moduledoc """
  Swift emitter over the exported JSON Schema — `Codable` models for a native
  app (`mix kiln.export.schema --format swift`).

  Like `KilnCMS.SchemaExport.TypeScript` it reads the schema **document**
  through `KilnCMS.SchemaExport.Walk`, so the two cannot disagree about what a
  field is. What is Swift's own:

    * Every content type, block, shared definition and inline object (a
      `:group` row, a media snapshot, a `columns` column) becomes a
      `public struct … : Codable, Hashable, Sendable`. Inline objects nest
      inside the struct that holds them, named after their key (`custom_fields`
      → `CustomFields`; an array's items take an `Item` suffix).
    * A key that is nullable **or** not required is an optional — the decoder's
      `decodeIfPresent` treats an absent key and a `null` alike.
    * Swift names are `lowerCamelCase`; a `CodingKeys` enum pins the JSON key
      exactly whenever the two differ. Keywords are back-ticked, and a key that
      collides with another after conversion keeps a sanitized spelling of its
      own.
    * A string `enum` becomes a `String`-backed enum with an `unknown(String)`
      case and hand-written `Codable`, so an option added on the server never
      fails a decode in an app already in the store.
    * The block union is `public indirect enum Block`, switching on `_type`,
      with `.unknown(type:)` for a block type this build does not know; the
      content types get the same treatment as `Document`, switching on `type`.
    * An open map (an object without `properties`), a multi-type union and
      anything unconstrained is `JSONValue`, a small enum bundled in the file.

  What Swift cannot express is dropped, as the TypeScript emitter drops it:
  `format` (a `date-time` is a `String`, not a `Date` — the decoder's date
  strategy is the app's call), numeric bounds, a `const` (the field is typed by
  its value, not pinned to it), and an open object's unknown keys (ignored on
  decode). The file needs only the Swift standard library.
  """

  alias KilnCMS.SchemaExport.Walk

  @indent "    "

  @conformances "Codable, Hashable, Sendable"

  # https://docs.swift.org/swift-book/documentation/the-swift-programming-language/lexicalstructure#Keywords-and-Punctuation
  @keywords ~w(associatedtype borrowing class consuming deinit enum extension fileprivate func
               import init inout internal let nonisolated open operator private precedencegroup
               protocol public rethrows static struct subscript typealias var break case catch
               continue default defer do else fallthrough for guard if in repeat return throw
               switch where while Any as await false is nil super throws true try
               associativity convenience didSet dynamic final get indirect infix lazy left
               mutating none nonmutating optional override postfix precedence prefix required
               right set some unowned weak willSet)

  # Back-ticks do not rescue these as a stored property: `self`/`Self`/`Type`
  # are special even quoted, and `hashValue` is `Hashable`'s own requirement.
  @unquotable ~w(self Self Type Protocol hashValue)

  # Names a nested type must not take: the standard-library types the file
  # spells, and what every struct already declares.
  @reserved_types ~w(String Int Double Bool Array Dictionary Optional Set Never Any Error
                     Decoder Encoder CodingKey CodingKeys Codable Hashable Sendable Type Self
                     Protocol JSONValue)

  @doc """
  Emit Swift source for a schema document from
  `KilnCMS.SchemaExport.json_schema/1`.
  """
  @spec emit(map()) :: String.t()
  def emit(document) do
    model = Walk.model(document)
    names = top_level_names(model)
    ctx = %{names: names, kinds: model.defs, reserved: MapSet.new(Map.values(names))}

    [
      header(model),
      section("Shared", Enum.map(model.shared, &declaration(&1, ctx))),
      section("Blocks", Enum.map(model.blocks, &declaration(&1, ctx))),
      section("Block union", [tagged_union("Block", model.block_union, ctx)]),
      section("Documents", Enum.map(model.documents, &declaration(&1, ctx))),
      section("Document union", [tagged_union("Document", model.document_union, ctx)]),
      section("JSONValue", [json_value()])
    ]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n")
  end

  defp header(model) do
    """
    // Generated by `mix kiln.export.schema --format swift`. Do not edit.
    //
    // The `:json` fired-artifact shape served by
    // `GET /api/content/:type/:slug?surface=json`.
    //
    // Artifact format version: #{model.format_version || "unknown"}
    """
  end

  defp section(title, declarations) do
    case Enum.reject(declarations, &(&1 == "")) do
      [] -> ""
      declarations -> "\n// MARK: - #{title}\n\n" <> Enum.join(declarations, "\n\n") <> "\n"
    end
  end

  # ── naming ──────────────────────────────────────────────────────────────────

  # `$defs` name → Swift type name, unique across the file. The bundled types
  # are claimed first, so a site whose content type happens to be called
  # `json_value` gets a suffixed name rather than shadowing the helper.
  defp top_level_names(model) do
    decls = model.shared ++ model.blocks ++ model.documents
    union = if model.block_union, do: [model.block_union.name], else: []
    taken = MapSet.new(~w(Block Document JSONValue))

    {names, _taken} =
      Enum.reduce(Enum.map(decls, & &1.name), {%{}, taken}, fn name, {acc, taken} ->
        swift = unique(base_type_name(name), taken)
        {Map.put(acc, name, swift), MapSet.put(taken, swift)}
      end)

    # Only the block union is reachable by `$ref`; `Document` is never a
    # `$defs` entry, so it takes no key here (a shared def called `document`
    # already holds that one).
    Map.merge(names, Map.new(union, &{&1, "Block"}))
  end

  defp base_type_name("block_" <> rest), do: upper_camel(rest) <> "Block"
  defp base_type_name("content_" <> rest), do: upper_camel(rest) <> "Document"
  defp base_type_name(name), do: upper_camel(name)

  defp unique(name, taken) do
    if MapSet.member?(taken, name),
      do: Enum.find_value(Stream.iterate(2, &(&1 + 1)), &if_free("#{name}#{&1}", taken)),
      else: name
  end

  defp if_free(name, taken), do: if(MapSet.member?(taken, name), do: nil, else: name)

  defp words(key), do: String.split(key, ~r/[^A-Za-z0-9]+/, trim: true)

  defp upper_camel(key) do
    key |> words() |> Enum.map_join("", &capitalize_first/1) |> leading_digit()
  end

  defp lower_camel(key) do
    case words(key) do
      [] ->
        "empty"

      [first | rest] ->
        (lower_first(first) <> Enum.map_join(rest, "", &capitalize_first/1)) |> leading_digit()
    end
  end

  defp capitalize_first(<<c::utf8, rest::binary>>), do: String.upcase(<<c::utf8>>) <> rest
  defp lower_first(<<c::utf8, rest::binary>>), do: String.downcase(<<c::utf8>>) <> rest

  defp leading_digit(""), do: "_"
  defp leading_digit(<<c, _::binary>> = name) when c in ?0..?9, do: "_" <> name
  defp leading_digit(name), do: name

  # The raw key with everything Swift rejects replaced — the fallback when two
  # keys camel-case to one name (`_type` beside `type`).
  defp sanitized(key), do: key |> String.replace(~r/[^A-Za-z0-9_]/, "_") |> leading_digit()

  # Swift property names for `fields`, in their order: keys whose camel-cased
  # form *is* the key claim it first, so a block's `type` field keeps `type`
  # and its `_type` discriminator falls back to `_type`.
  defp property_names(fields) do
    keys = Enum.map(fields, & &1.key)
    {exact, converted} = Enum.split_with(keys, &(lower_camel(&1) == &1))

    {names, _taken} =
      Enum.reduce(exact ++ converted, {%{}, MapSet.new()}, fn key, {acc, taken} ->
        name = pick_name([lower_camel(key), sanitized(key)], taken)
        {Map.put(acc, key, name), MapSet.put(taken, name)}
      end)

    names
  end

  defp pick_name(candidates, taken) do
    candidates = Enum.map(candidates, &unquotable/1)
    Enum.find(candidates, &(not MapSet.member?(taken, &1))) || unique(hd(candidates), taken)
  end

  defp unquotable(name) when name in @unquotable, do: name <> "_"
  defp unquotable(name), do: name

  defp ident(name) when name in @keywords, do: "`#{name}`"
  defp ident(name), do: name

  # ── declarations ────────────────────────────────────────────────────────────

  defp declaration(%{shape: :opaque} = decl, ctx),
    do: doc(decl.description, "") <> "public typealias #{ctx.names[decl.name]} = JSONValue"

  defp declaration(%{shape: {:object, fields, _open?}} = decl, ctx) do
    struct(ctx.names[decl.name], decl.description, fields, "", ctx)
  end

  defp struct(name, description, fields, indent, ctx) do
    inner = indent <> @indent
    props = property_names(fields)
    scope = %{ctx | reserved: MapSet.put(ctx.reserved, name)}

    {members, nested, _scope} =
      Enum.reduce(fields, {[], [], scope}, fn field, {members, nested, scope} ->
        {swift, optional?, decls, scope} = swift_type(field.type, field.key, false, inner, scope)
        optional? = optional? or not field.required?
        member = %{field: field, name: props[field.key], type: swift, optional?: optional?}
        {[member | members], nested ++ decls, scope}
      end)

    members = Enum.reverse(members)

    body =
      [
        Enum.map_join(members, "\n", &property(&1, inner)),
        initializer(members, inner),
        coding_keys(members, inner)
        | nested
      ]
      |> Enum.reject(&(&1 == ""))
      |> Enum.join("\n\n")

    doc(description, indent) <>
      "#{indent}public struct #{name}: #{@conformances} {\n" <>
      if(body == "", do: "", else: body <> "\n") <> "#{indent}}"
  end

  defp property(member, indent) do
    doc(field_doc(member.field), indent) <>
      "#{indent}public let #{ident(member.name)}: #{type_ref(member)}"
  end

  defp type_ref(%{optional?: true, type: type}), do: type <> "?"
  defp type_ref(%{type: type}), do: type

  defp field_doc(%{description: description, target_types: types}) do
    links = if types == [], do: nil, else: "Links to: #{Enum.map_join(types, ", ", &"`#{&1}`")}."
    [description, links] |> Enum.reject(&is_nil/1) |> Enum.join("\n\n") |> nil_if_empty()
  end

  defp nil_if_empty(""), do: nil
  defp nil_if_empty(text), do: text

  # Public, because a synthesized memberwise init is internal — an app could
  # decode these but never build one for a preview or a test.
  defp initializer(members, indent) do
    inner = indent <> @indent

    params =
      Enum.map_join(members, ", ", fn member ->
        default = if member.optional?, do: " = nil", else: ""
        "#{ident(member.name)}: #{type_ref(member)}#{default}"
      end)

    assignments =
      Enum.map_join(members, "\n", fn member ->
        "#{inner}self.#{ident(member.name)} = #{ident(member.name)}"
      end)

    body = if assignments == "", do: "", else: "\n" <> assignments <> "\n" <> indent

    "#{indent}public init(#{params}) {#{body}}"
  end

  defp coding_keys(members, indent) do
    if Enum.all?(members, &(&1.name == &1.field.key)) do
      ""
    else
      inner = indent <> @indent

      cases = Enum.map_join(members, "\n", &"#{inner}case #{ident(&1.name)}#{raw_value(&1)}")
      "#{indent}enum CodingKeys: String, CodingKey {\n#{cases}\n#{indent}}"
    end
  end

  defp raw_value(%{name: key, field: %{key: key}}), do: ""
  defp raw_value(%{field: %{key: key}}), do: " = " <> literal(key)

  # ── type mapping ────────────────────────────────────────────────────────────

  # `{swift_type, optional?, nested_declarations, scope}`. `key` names any type
  # this has to hoist; `item?` says it is an array's element (→ `…Item`).
  defp swift_type({:ref, name}, _key, _item?, _indent, scope) do
    swift =
      case scope.kinds[name] do
        kind when kind in [:object, :opaque] -> scope.names[name]
        :union -> if scope.names[name] == "Block", do: "Block", else: "JSONValue"
        nil -> "JSONValue"
      end

    {swift, false, [], scope}
  end

  defp swift_type({:nullable, inner}, key, item?, indent, scope) do
    {swift, _optional?, decls, scope} = swift_type(inner, key, item?, indent, scope)
    {swift, true, decls, scope}
  end

  defp swift_type({:union, [one]}, key, item?, indent, scope),
    do: swift_type(one, key, item?, indent, scope)

  defp swift_type({:union, _many}, _key, _item?, _indent, scope),
    do: {"JSONValue", false, [], scope}

  defp swift_type({:const, value}, _key, _item?, _indent, scope),
    do: {value_type([value]), is_nil(value), [], scope}

  defp swift_type({:enum, values}, key, item?, indent, scope) do
    {nils, values} = Enum.split_with(values, &is_nil/1)
    optional? = nils != []

    if values != [] and Enum.all?(values, &is_binary/1) do
      {name, scope} = nested_name(key, item?, scope)
      {name, optional?, [open_enum(name, Enum.uniq(values), indent)], scope}
    else
      {value_type(values), optional?, [], scope}
    end
  end

  defp swift_type({:array, items}, key, _item?, indent, scope) do
    {swift, optional?, decls, scope} = swift_type(items, key, true, indent, scope)
    element = if optional?, do: swift <> "?", else: swift
    {"[" <> element <> "]", false, decls, scope}
  end

  defp swift_type({:object, fields, _open?}, key, item?, indent, scope) do
    {name, scope} = nested_name(key, item?, scope)
    {name, false, [struct(name, nil, fields, indent, scope)], scope}
  end

  defp swift_type(:map, _key, _item?, _indent, scope),
    do: {"[String: JSONValue]", false, [], scope}

  defp swift_type(:integer, _key, _item?, _indent, scope), do: {"Int", false, [], scope}
  defp swift_type(:number, _key, _item?, _indent, scope), do: {"Double", false, [], scope}
  defp swift_type(:boolean, _key, _item?, _indent, scope), do: {"Bool", false, [], scope}
  defp swift_type(:string, _key, _item?, _indent, scope), do: {"String", false, [], scope}
  defp swift_type(:null, _key, _item?, _indent, scope), do: {"JSONValue", true, [], scope}
  defp swift_type(:unknown, _key, _item?, _indent, scope), do: {"JSONValue", false, [], scope}

  # The Swift type of a literal's values — a `const` is typed, never pinned.
  defp value_type([]), do: "JSONValue"

  defp value_type(values) do
    cond do
      Enum.all?(values, &is_binary/1) -> "String"
      Enum.all?(values, &is_boolean/1) -> "Bool"
      Enum.all?(values, &is_integer/1) -> "Int"
      Enum.all?(values, &is_number/1) -> "Double"
      true -> "JSONValue"
    end
  end

  # A nested type's name must not shadow a top-level type (a key `block`
  # would otherwise hide `Block` from everything nested below it), a sibling,
  # or an enclosing struct.
  defp nested_name(key, item?, scope) do
    base = upper_camel(key) <> if(item?, do: "Item", else: "")
    taken = MapSet.union(scope.reserved, MapSet.new(@reserved_types))
    name = if MapSet.member?(taken, base), do: unique(base <> "Value", taken), else: base
    {name, %{scope | reserved: MapSet.put(scope.reserved, name)}}
  end

  # ── enums ───────────────────────────────────────────────────────────────────

  defp open_enum(name, values, indent) do
    i1 = indent <> @indent
    i2 = i1 <> @indent
    cases = enum_cases(values, [])

    """
    #{indent}public enum #{name}: RawRepresentable, #{@conformances} {
    #{Enum.map_join(cases, "\n", fn {_value, c} -> "#{i1}case #{ident(c)}" end)}
    #{i1}/// A value this schema does not list — an option added since it was generated.
    #{i1}case unknown(String)

    #{i1}public init(rawValue: String) {
    #{i2}switch rawValue {
    #{Enum.map_join(cases, "\n", fn {value, c} -> "#{i2}case #{literal(value)}: self = .#{ident(c)}" end)}
    #{i2}default: self = .unknown(rawValue)
    #{i2}}
    #{i1}}

    #{i1}public var rawValue: String {
    #{i2}switch self {
    #{Enum.map_join(cases, "\n", fn {value, c} -> "#{i2}case .#{ident(c)}: return #{literal(value)}" end)}
    #{i2}case .unknown(let value): return value
    #{i2}}
    #{i1}}

    #{i1}public init(from decoder: Decoder) throws {
    #{i2}self.init(rawValue: try decoder.singleValueContainer().decode(String.self))
    #{i1}}

    #{i1}public func encode(to encoder: Encoder) throws {
    #{i2}var container = encoder.singleValueContainer()
    #{i2}try container.encode(rawValue)
    #{i1}}
    #{indent}}\
    """
  end

  # `{value, case_name}` in value order. `unknown` is the fallback's, and a
  # union also reserves the `type` accessor it declares.
  defp enum_cases(values, reserved) do
    {cases, _taken} =
      Enum.reduce(values, {[], MapSet.new(["unknown" | reserved])}, fn value, {acc, taken} ->
        name = pick_name([lower_camel(value), sanitized(value)], taken)
        {[{value, name} | acc], MapSet.put(taken, name)}
      end)

    Enum.reverse(cases)
  end

  # ── tagged unions ───────────────────────────────────────────────────────────

  defp tagged_union(_name, nil, _ctx), do: ""
  defp tagged_union(_name, %{members: []}, _ctx), do: ""

  defp tagged_union(name, %{tag: tag, members: members}, ctx) do
    # A member without a `const` tag cannot be told apart on the wire, so it
    # gets no case; it decodes as `.unknown` like any other unlisted type.
    members = Enum.filter(members, &(is_binary(&1.tag) and Map.has_key?(ctx.names, &1.def)))
    cases = enum_cases(Enum.map(members, & &1.tag), ["type"])
    rows = Enum.zip(members, Enum.map(cases, &elem(&1, 1)))
    i1 = @indent
    i2 = i1 <> @indent
    i3 = i2 <> @indent

    what = if name == "Block", do: "block", else: "content"

    """
    /// Any #{what} in a fired `:json` artifact, told apart by `#{tag}`.
    public indirect enum #{name}: #{@conformances} {
    #{Enum.map_join(rows, "\n", fn {m, c} -> "#{i1}case #{ident(c)}(#{ctx.names[m.def]})" end)}
    #{i1}/// A #{what} type this build does not know — one added after it was generated.
    #{i1}case unknown(type: String)

    #{i1}private enum TagKey: String, CodingKey {
    #{i2}case tag = #{literal(tag)}
    #{i1}}

    #{i1}public var type: String {
    #{i2}switch self {
    #{Enum.map_join(rows, "\n", fn {m, c} -> "#{i2}case .#{ident(c)}: return #{literal(m.tag)}" end)}
    #{i2}case .unknown(let type): return type
    #{i2}}
    #{i1}}

    #{i1}public init(from decoder: Decoder) throws {
    #{i2}let type = try decoder.container(keyedBy: TagKey.self).decode(String.self, forKey: .tag)
    #{i2}switch type {
    #{Enum.map_join(rows, "\n", fn {m, c} -> "#{i2}case #{literal(m.tag)}: self = .#{ident(c)}(try #{ctx.names[m.def]}(from: decoder))" end)}
    #{i2}default: self = .unknown(type: type)
    #{i2}}
    #{i1}}

    #{i1}public func encode(to encoder: Encoder) throws {
    #{i2}switch self {
    #{Enum.map_join(rows, "\n", fn {_m, c} -> "#{i2}case .#{ident(c)}(let value): try value.encode(to: encoder)" end)}
    #{i2}case .unknown(let type):
    #{i3}var container = encoder.container(keyedBy: TagKey.self)
    #{i3}try container.encode(type, forKey: .tag)
    #{i2}}
    #{i1}}
    }\
    """
  end

  defp json_value do
    """
    /// Any JSON value — what an open map, an unconstrained field or a union
    /// Swift cannot name decodes to.
    public indirect enum JSONValue: #{@conformances} {
        case null
        case bool(Bool)
        case number(Double)
        case string(String)
        case array([JSONValue])
        case object([String: JSONValue])

        public init(from decoder: Decoder) throws {
            let container = try decoder.singleValueContainer()
            if container.decodeNil() {
                self = .null
            } else if let value = try? container.decode(Bool.self) {
                self = .bool(value)
            } else if let value = try? container.decode(Double.self) {
                self = .number(value)
            } else if let value = try? container.decode(String.self) {
                self = .string(value)
            } else if let value = try? container.decode([JSONValue].self) {
                self = .array(value)
            } else {
                self = .object(try container.decode([String: JSONValue].self))
            }
        }

        public func encode(to encoder: Encoder) throws {
            var container = encoder.singleValueContainer()
            switch self {
            case .null: try container.encodeNil()
            case .bool(let value): try container.encode(value)
            case .number(let value): try container.encode(value)
            case .string(let value): try container.encode(value)
            case .array(let value): try container.encode(value)
            case .object(let value): try container.encode(value)
            }
        }
    }\
    """
  end

  # ── literals ────────────────────────────────────────────────────────────────

  defp doc(nil, _indent), do: ""

  defp doc(text, indent) do
    text
    |> String.split(~r/\r\n|\r|\n/)
    |> Enum.map_join("", fn
      "" -> "#{indent}///\n"
      line -> "#{indent}/// #{line}\n"
    end)
  end

  # Custom-field names and `:select` options are admin input with no charset
  # validation; a quote or a control character in one must not end the
  # literal early or break the file.
  defp literal(value) do
    escaped =
      value
      |> String.to_charlist()
      |> Enum.map_join(fn
        ?\\ -> "\\\\"
        ?" -> "\\\""
        ?\n -> "\\n"
        ?\r -> "\\r"
        ?\t -> "\\t"
        c when c < 0x20 or c == 0x7F -> "\\u{#{Integer.to_string(c, 16)}}"
        c -> <<c::utf8>>
      end)

    ~s(") <> escaped <> ~s(")
  end
end
