defmodule Mix.Tasks.Kiln.Reporting.Sql do
  @shortdoc "Print the SQL that creates a read-only BI role for the reporting views"
  @moduledoc """
  Prints (never runs) a SQL script that creates a read-only Postgres role for
  BI tools such as Metabase, Superset or Looker Studio (#2295).

      mix kiln.reporting.sql > kiln_bi.sql
      mix kiln.reporting.sql --role kiln_bi --database kiln_cms_prod

  The role is granted `SELECT` on the views in the `kiln_reporting_v1` schema
  and nothing else. Kiln's tables are not readable by `PUBLIC` in a standard
  install, so the base tables, user accounts, secrets and unpublished drafts
  are out of reach of a role holding only these grants; the script's
  `REVOKE` removes only grants made to the role by name, and the notes in the
  script say what to check where `PUBLIC` has been given more. The task
  connects to no database; read the script, replace the placeholder password,
  and run it with `psql`. Its role settings are advisory (a role can reset
  them); use a read replica for hard enforcement.

  ## Options

    * `--role NAME`: the role to create (default `kiln_bi`). Must match
      `^[a-z_][a-z0-9_]{0,62}$`; anything else is refused.
    * `--database NAME`: also grant `CONNECT` on this database (same rules as
      a role name).

  The view list comes from the compiled content types, so overlay types are
  included. Run the script after the migration that created the views, and
  again after an upgrade that adds views: grants cover existing views only.
  """

  use Mix.Task

  alias KilnCMS.CMS.ContentTypes
  alias KilnCMS.Reporting.ViewSql

  @default_role "kiln_bi"
  @identifier ~r/\A[a-z_][a-z0-9_]{0,62}\z/

  @impl Mix.Task
  def run(args) do
    {opts, _rest, invalid} =
      OptionParser.parse(args, strict: [role: :string, database: :string])

    if invalid != [], do: Mix.raise("Unknown or malformed options: #{inspect(invalid)}")

    # Compiles and loads the app (no database, nothing started): the view list
    # asks resource modules for their markers, and an unloaded module answers
    # none.
    Mix.Task.run("app.config")

    role = identifier!(Keyword.get(opts, :role, @default_role), "--role")
    database = opts |> Keyword.get(:database) |> database!()

    Mix.shell().info(script(role, database))

    Mix.shell().error(
      "Note: re-run this script after any upgrade that adds reporting views; " <>
        "a GRANT covers the views that exist when it runs."
    )
  end

  @doc "The script for `role` (and `database`, when given), as one string."
  @spec script(String.t(), String.t() | nil) :: String.t()
  def script(role, database \\ nil) do
    r = quote_ident(role)
    schema = ViewSql.schema()

    connect =
      if database,
        do: "GRANT CONNECT ON DATABASE #{quote_ident(database)} TO #{r};\n",
        else: ""

    """
    -- KilnCMS read-only reporting role (#2295). Generated by `mix kiln.reporting.sql`;
    -- nothing has been run. Read it, then apply it with psql.
    --
    -- * Run as a role that may create roles. Managed Postgres often withholds
    --   CREATEROLE from the app user: use the provider's console instead.
    -- * Point the BI tool at a read replica, not the primary, and require SSL
    --   (sslmode=verify-full) on its connection.
    -- * This role sees every organization's published public rows. Do not hand
    --   it to a tenant.
    -- * Replace the placeholder password before running. Do not commit it.
    -- * Re-run the GRANT lines after an upgrade that adds views (a new content
    --   type, a new release): a grant covers the views that exist when it runs.
    -- * The settings at the end are advisory. The role can SET
    --   default_transaction_read_only off for itself, so it is a guard against
    --   mistakes, not a control. For hard enforcement connect to a read replica.
    -- * REVOKE ... FROM the role removes only what was granted to it by name.
    --   Whatever PUBLIC may do in the public schema is unchanged; on a database
    --   where PUBLIC can read tables there, also run
    --   REVOKE ALL ON SCHEMA public FROM PUBLIC (PostgreSQL 15 and later
    --   already withhold CREATE).

    CREATE ROLE #{r} LOGIN PASSWORD 'REPLACE_WITH_A_LONG_RANDOM_PASSWORD';

    -- Removes only grants made to this role itself, not those held by PUBLIC.
    REVOKE ALL ON SCHEMA public FROM #{r};
    #{connect}GRANT USAGE ON SCHEMA #{schema} TO #{r};

    #{grants(r)}

    ALTER ROLE #{r} SET search_path = #{schema};
    ALTER ROLE #{r} SET statement_timeout = '60s';
    ALTER ROLE #{r} SET default_transaction_read_only = on;
    """
  end

  @doc "The view names the script grants: each content table and its field-values view."
  @spec views() :: [String.t()]
  def views do
    # The generic entry tier backs every dynamic type but is not in
    # `ContentTypes.all/0` (it has no type of its own), so it is added by its
    # marker; the view migration emitted its views too.
    ContentTypes.content_domains()
    |> Enum.flat_map(&Ash.Domain.Info.resources/1)
    |> Enum.map(&Code.ensure_loaded!/1)
    |> Enum.filter(
      &(function_exported?(&1, :__kiln_content_type__, 0) or
          function_exported?(&1, :__kiln_dynamic_entry__, 0))
    )
    |> Enum.map(&AshPostgres.DataLayer.Info.table/1)
    |> Enum.uniq()
    |> Enum.sort()
    |> Enum.flat_map(&[&1, "#{&1}_field_values"])
  end

  defp grants(role) do
    Enum.map_join(views(), "\n", &"GRANT SELECT ON #{ViewSql.schema()}.#{&1} TO #{role};")
  end

  defp database!(nil), do: nil
  defp database!(name), do: identifier!(name, "--database")

  defp identifier!(name, flag) do
    if Regex.match?(@identifier, name) do
      name
    else
      Mix.raise("#{flag} must match #{inspect(Regex.source(@identifier))}, got #{inspect(name)}")
    end
  end

  defp quote_ident(name), do: ~s("#{name}")
end
