defmodule KilnCMSWeb.ContentController do
  @moduledoc """
  Public content delivery — renders **published** content as HTML for anonymous
  site visitors (the human-facing counterpart to the headless GraphQL/JSON:API
  endpoints).

  URL structure matches the sitemap: pages at `/<slug>`, posts at
  `/blog/<slug>` (plus a `/blog` index), and every other content type at
  `/<plural>/<slug>` (resolved generically through `KilnCMS.CMS.ContentTypes`).
  Only published content is reachable; the read actions filter on
  `state == :published`, so an unpublished slug 404s rather than leaking a draft.
  """
  use KilnCMSWeb, :controller

  alias KilnCMS.Cache
  alias KilnCMS.CMS
  alias KilnCMS.CMS.ContentTypes
  alias KilnCMS.Feeds
  alias KilnCMS.I18n
  alias KilnCMSWeb.Params
  alias KilnCMSWeb.StructuredData
  alias KilnCMSWeb.ViewTracking

  def show_page(conn, %{"slug" => slug}) do
    locale = locale(conn)
    ct = ContentTypes.get(:page)
    org_id = current_org_id(conn)
    audiences = reader_audiences(conn)

    fetch =
      &CMS.get_published_page_by_slug!(slug, &1, %{audiences: audiences},
        not_found_error?: false,
        authorize?: false,
        tenant: org_id,
        load: [:author]
      )

    case fetch_payload(org_id, "page", slug, locale, audiences, fn ->
           payload(fetch, locale, ct, org_id, audiences)
         end) do
      nil ->
        follow_redirect_or_404(conn, "/" <> slug, ct)

      payload ->
        serve(conn, :show_page, "page", payload, ct, audiences)
    end
  end

  def show_post(conn, %{"slug" => slug}) do
    locale = locale(conn)
    ct = ContentTypes.get(:post)
    org_id = current_org_id(conn)
    audiences = reader_audiences(conn)

    fetch =
      &CMS.get_published_post_by_slug!(slug, &1, %{audiences: audiences},
        not_found_error?: false,
        authorize?: false,
        tenant: org_id,
        load: [:author]
      )

    case fetch_payload(org_id, "post", slug, locale, audiences, fn ->
           payload(fetch, locale, ct, org_id, audiences)
         end) do
      nil ->
        follow_redirect_or_404(conn, "/blog/" <> slug, ct)

      payload ->
        serve(conn, :show_post, "post", payload, ct, audiences)
    end
  end

  # Generic delivery for any other content type at `/<plural>/<slug>` (e.g. a
  # type generated by `mix kiln.gen.content`). `type` is the URL segment.
  def show_content(conn, %{"type" => type, "slug" => slug}) do
    locale = locale(conn)
    org_id = current_org_id(conn)
    audiences = reader_audiences(conn)
    ct = ContentTypes.get_by_path(type, org_id)

    with ct when not is_nil(ct) <- ct,
         fetch =
           &ContentTypes.get_published_by_slug(ct.type, slug, &1,
             audiences: audiences,
             not_found_error?: false,
             authorize?: false,
             tenant: org_id,
             load: [:author]
           ),
         payload when not is_nil(payload) <-
           fetch_payload(org_id, to_string(ct.type), slug, locale, audiences, fn ->
             payload(fetch, locale, ct, org_id, audiences)
           end) do
      serve(conn, :show, to_string(ct.type), payload, ct, audiences)
    else
      _ -> follow_redirect_or_404(conn, "/" <> type <> "/" <> slug, ct)
    end
  end

  # Serve a payload at its canonical URL: a record with a `path_alias` (#485)
  # 301s its flat `/<prefix>/<slug>` URL to the alias; everything else renders.
  defp serve(conn, view, type_string, payload, ct, audiences) do
    alias_path = Map.get(payload.record, :path_alias)

    if is_binary(alias_path) and conn.request_path != alias_path do
      moved_permanently(conn, alias_path)
    else
      ViewTracking.track(:html, type_string, payload.record.id, payload.record.org_id)
      render_content(conn, view, payload, ct, audiences)
    end
  end

  # Deep paths (3+ segments) carry no content routes — they exist only as
  # redirect sources, e.g. a legacy `/2019/05/old-post` imported from a
  # previous site (#457).
  def fallback(conn, %{"path" => segments}) do
    follow_redirect_or_404(conn, "/" <> Enum.join(segments, "/"))
  end

  # Every URL miss funnels here: first a multi-segment path alias (#485) —
  # the canonical home of aliased content — then the redirect table (a
  # published rename leaves a `CMS.Redirect` behind; resolution is live, no
  # chains); anything unresolvable 404s as before.
  # `ct` (when known) lets the flat-slug miss try a paywall teaser for that type.
  #
  # Order matters: alias, then the redirect table, then the teaser, then 404. The
  # teaser is LAST so a gated document that also has a legacy redirect still
  # redirects — a paywall must not shadow an editor's explicit routing decision.
  defp follow_redirect_or_404(conn, path, ct \\ nil) do
    serve_alias(conn, path) ||
      case KilnCMS.CMS.Redirects.resolve(path, locale(conn), current_org_id(conn)) do
        nil ->
          serve_teaser(conn, path, ct) || not_found(conn)

        %{to: to} ->
          moved_permanently(conn, to)
      end
  end

  # Render a paywall for a GATED published document the reader can't read.
  #
  # Only reached once the entitled lookup, the alias lookup and the redirect table
  # have all missed — so a reader who IS entitled never sees a paywall, and a
  # genuinely unknown slug still 404s. The read requires a non-public audience and
  # never selects the block tree; the record is then projected onto
  # `KilnCMSWeb.Teaser`, which has no `blocks` field at all.
  defp serve_teaser(_conn, _path, nil), do: nil

  defp serve_teaser(conn, path, ct) do
    slug = path |> String.split("/") |> List.last()
    locale = locale(conn)
    org_id = current_org_id(conn)

    fetch = fn loc ->
      ContentTypes.get_teaser_by_slug(ct.type, slug, loc,
        not_found_error?: false,
        authorize?: false,
        tenant: org_id
      )
    end

    case localized(fetch, locale) do
      nil -> nil
      record -> render_teaser(conn, record, ct)
    end
  rescue
    # A content type without a teaser interface (an overlay compiled against an
    # older macro) simply has no paywall — 404 as before rather than 500.
    _ -> nil
  end

  defp render_teaser(conn, record, ct) do
    org = KilnCMSWeb.Tenant.current_org(conn)
    base_url = KilnCMSWeb.Tenant.base_url(org)
    url = record.canonical_url || locale_url(ct, record.slug, record.locale, base_url)
    teaser = KilnCMSWeb.Teaser.from_record(record, url)

    conn
    # Same rule as a member render: this body depends on who asked, and the same
    # URL returns the full document for an entitled reader — a shared cache keyed
    # on URL alone would eventually cross the two.
    |> put_private_delivery_headers()
    |> assign(:locale, teaser.locale)
    |> assign(:page_title, teaser.seo_title || teaser.title)
    |> assign(:meta_description, teaser.seo_description)
    |> assign(:og_image, teaser.seo_image)
    |> assign(:og_type, "article")
    # Canonical is the DOCUMENT's own URL, never the join page: a paywall that
    # canonicalised elsewhere would have search engines index the wrong URL.
    |> assign(:canonical_url, teaser.url)
    |> assign(:json_ld, json_ld_script(StructuredData.teaser(teaser, org)))
    |> put_view(KilnCMSWeb.ContentHTML)
    |> render(:teaser, teaser: teaser)
  end

  # 301 to a canonical (unprefixed) delivery path, restoring the locale prefix
  # the visitor arrived through — `/fr/old-slug` lands on `/fr/new-slug` rather
  # than dumping a French reader on the default locale's URL. Only a *path*
  # prefix is re-applied (`Plugs.SetLocale` strips it into `:path_locale`),
  # never a session preference: the destination has to stay a pure function of
  # the requested URL, since a 301 without `Vary` is cacheable by shared caches.
  defp moved_permanently(conn, path) do
    conn
    |> put_status(:moved_permanently)
    |> redirect(to: I18n.localized_path(conn.assigns[:path_locale], path))
  end

  # Render the published record whose `path_alias` is this path, through the
  # same payload pipeline as the flat routes (uncached: alias hits are already
  # the miss path, and slug-keyed cache busting can't see alias keys).
  defp serve_alias(conn, path) do
    locale = locale(conn)
    org_id = current_org_id(conn)

    audiences = reader_audiences(conn)

    lookup = fn loc ->
      KilnCMS.CMS.Slugs.find_published_by_alias(path, loc, org_id, audiences)
    end

    case lookup.(locale) || lookup.(I18n.default_locale()) do
      nil ->
        teaser_alias(conn, path, locale, org_id)

      {ct, record} ->
        payload = %{
          record: record,
          blocks: blocks(record, org_id),
          translations: translations(ct, record.slug, org_id, audiences)
        }

        serve(conn, alias_view(ct), to_string(ct.type), payload, ct, audiences)
    end
  end

  # An aliased document that is gated for this reader: paywall at the alias, so a
  # canonical URL doesn't silently 404.
  defp teaser_alias(conn, path, locale, org_id) do
    lookup = fn loc -> KilnCMS.CMS.Slugs.find_teaser_by_alias(path, loc, org_id) end

    case lookup.(locale) || lookup.(I18n.default_locale()) do
      nil -> nil
      {ct, record} -> render_teaser(conn, record, ct)
    end
  end

  defp alias_view(%{type: :page}), do: :show_page
  defp alias_view(%{type: :post}), do: :show_post
  defp alias_view(_ct), do: :show

  # Posts shown per page on the public blog index. Bounds per-request memory/DB
  # load — the `:published` read is paginated and capped at its `max_page_size`.
  @blog_page_size 20

  def blog_index(conn, params) do
    locale = locale(conn)
    page = page_param(params)
    org = KilnCMSWeb.Tenant.current_org(conn)

    # No `count: true` — only `more?` is used, and a count adds a full
    # COUNT(*) over published posts to every request.
    %Ash.Page.Offset{results: posts, more?: more?} =
      CMS.list_published_posts!(
        authorize?: false,
        tenant: org.id,
        query: [filter: [locale: locale]],
        page: [limit: @blog_page_size, offset: page * @blog_page_size]
      )

    conn
    |> put_resp_header("cache-control", "public, max-age=60, stale-while-revalidate=300")
    |> put_resp_header("vary", "Accept-Language")
    |> assign(:locale, locale)
    |> assign(:page_title, gettext("Blog"))
    |> assign(:meta_description, gettext("Latest posts."))
    |> assign(:locale_links, blog_locale_links(locale, KilnCMSWeb.Tenant.base_url(org)))
    |> assign(:json_ld, json_ld_script(StructuredData.blog(posts, org)))
    |> render(:blog_index, posts: posts, page: page, has_prev?: page > 0, has_next?: more?)
  end

  # Public on-site search (#149). Anonymous, so the read policy returns published
  # content only; locale-scoped to the active locale. Posts, pages and dynamic
  # entries (media isn't part of the public site).
  def search(conn, params) do
    locale = locale(conn)
    query = params |> Params.string("q", "") |> String.trim()
    # Scope search to the request's org (#336); content sections are per-site.
    org = KilnCMSWeb.Tenant.current_org(conn)
    org_id = org.id

    # Optional category facet (`?category=<slug>`): filters both hybrid legs.
    # An unknown slug matches nothing rather than silently unfiltering. Resolved
    # within the request org so a foreign site's category can't be referenced.
    category = category_filter(params["category"], org_id)

    filters =
      case category do
        %{id: id} -> %{category_id: id}
        :unknown -> %{category_id: Ecto.UUID.generate()}
        nil -> %{}
      end

    results =
      if query == "" do
        %{posts: [], pages: [], entries: []}
      else
        r =
          KilnCMS.Search.global(query,
            authorize?: true,
            tenant: org_id,
            locale: locale,
            limit: 20,
            filters: filters
          )

        %{posts: r.posts, pages: r.pages, entries: entry_results(r.entries)}
      end

    # Category counts over the unfiltered match set — the sidebar shows the
    # full distribution to switch between (tag facets are API-only for now).
    facets =
      if query == "",
        do: [],
        else:
          KilnCMS.Search.facets(query, authorize?: true, tenant: org_id, locale: locale).categories

    # A sparse result set gets a trigram "did you mean" (published titles
    # only) — the fuzzy hybrid leg may have rescued a typo's hits, and the
    # suggestion then names the corrected term. Exact-match queries never
    # suggest (`Search.suggest/2` skips exact word matches).
    total = length(results.posts) + length(results.pages) + length(results.entries)

    suggestion =
      if query != "" and total < 3,
        do: KilnCMS.Search.suggest(query, authorize?: true, tenant: org_id, locale: locale)

    conn
    # Don't cache personalized/empty query result pages on shared caches.
    |> put_resp_header("cache-control", "private, no-cache")
    |> assign(:locale, locale)
    |> assign(:page_title, gettext("Search"))
    |> assign(:locale_links, search_locale_links(locale, query, KilnCMSWeb.Tenant.base_url(org)))
    |> render(:search,
      query: query,
      results: results,
      suggestion: suggestion,
      facets: facets,
      active_category: if(is_struct(category), do: category)
    )
  end

  # Resolve a `?category=` slug world-readably: nil when absent, the category
  # when known, `:unknown` otherwise.
  defp category_filter(slug, org_id) when is_binary(slug) and slug != "" do
    case KilnCMS.CMS.get_category_by_slug(slug, authorize?: true, tenant: org_id) do
      {:ok, category} -> category
      _not_found -> :unknown
    end
  end

  defp category_filter(_absent, _org_id), do: nil

  # Dynamic-entry hits as plain view maps: resolve each result's type through
  # the registry for its URL segment and label, dropping hits whose type no
  # longer resolves (archived between indexing and render). The registry is
  # per-org (#336), so each hit resolves against its OWN org rather than
  # `get_dynamic/1`'s default-org fallback.
  defp entry_results(entries) do
    Enum.flat_map(entries, fn entry ->
      case ContentTypes.get_dynamic(entry.type_name, entry.org_id) do
        %{path_segment: segment, label: label} ->
          [
            %{
              title: entry.title,
              excerpt: Map.get(entry, :excerpt),
              path: "/#{segment}/#{entry.slug}",
              type_label: label
            }
          ]

        _archived ->
          []
      end
    end)
  end

  # Language-switcher links to the search page (preserving the query) per locale.
  defp search_locale_links(current, query, base_url) do
    suffix = if query == "", do: "", else: "?q=#{URI.encode_www_form(query)}"

    for locale <- I18n.locales() do
      prefix = if locale == I18n.default_locale(), do: "", else: "/#{locale}"

      %{
        locale: locale,
        href: "#{base_url}#{prefix}/search#{suffix}",
        current: locale == current
      }
    end
  end

  # Highest zero-based page index we'll serve. Clamps `?page=N` so a huge value
  # can't force Postgres into a massive OFFSET + full COUNT scan (cheap DoS).
  @max_page 500

  # Zero-based page index from `?page=N` (1-based in the URL for humans).
  # Anything missing or invalid is page 0; anything beyond @max_page is clamped.
  defp page_param(%{"page" => raw}) when is_binary(raw) do
    case Integer.parse(raw) do
      {n, _} when n > 1 -> min(n - 1, @max_page)
      _ -> 0
    end
  end

  defp page_param(_params), do: 0

  # Language-switcher links to the blog index in each supported locale.
  defp blog_locale_links(current, base_url) do
    for locale <- I18n.locales() do
      prefix = if locale == I18n.default_locale(), do: "", else: "/#{locale}"
      %{locale: locale, href: "#{base_url}#{prefix}/blog", current: locale == current}
    end
  end

  # The requested locale (set by `KilnCMSWeb.Plugs.SetLocale`).
  defp locale(conn), do: conn.assigns[:locale] || I18n.default_locale()

  defp current_org_id(conn), do: KilnCMSWeb.Tenant.current_org_id(conn)

  # The gated audiences this reader holds (#337 Phase 2). The `:browser` pipeline
  # already runs `:load_from_session` on the delivery scope, so the signed-in user
  # is here for free — it was simply unused before.
  #
  # Filtered through `Audiences.valid?/1`: an audience dropped from
  # `config :kiln_cms, :audiences` could still sit on a user row, and passing a
  # stale atom into the action's `one_of` constraint would raise — a 500 on a
  # public page. Sorted so the value is stable.
  defp reader_audiences(conn) do
    case conn.assigns[:current_user] do
      %{audiences: audiences} when is_list(audiences) ->
        audiences |> Enum.filter(&KilnCMS.CMS.Audiences.valid?/1) |> Enum.uniq() |> Enum.sort()

      _other ->
        []
    end
  end

  # The `payload` cache namespace is the ANONYMOUS, `:public`-only shape, and it
  # stays that way: a reader with audiences bypasses it entirely.
  #
  # Bypassing rather than adding an audience axis to the key is deliberate. The
  # key is a string, so correctness would depend on canonically serialising a
  # SET — `[:member, :pro]` and `[:pro, :member]` are the same entitlement but
  # different strings — and any normalisation slip, or one caller forgetting the
  # component, would serve gated blocks to anonymous readers. Bypassing makes
  # that class of bug unreachable: gated payloads are never in the cache at all.
  # The cost is one query per gated page view, for the smallest and least
  # latency-sensitive slice of traffic.
  defp fetch_payload(org_id, type, slug, locale, [], fun),
    do: Cache.fetch_published_payload(org_id, type, slug, locale, fun)

  defp fetch_payload(_org_id, _type, _slug, _locale, _audiences, fun), do: fun.()

  # The cached delivery payload: the published record, its media-enriched blocks,
  # and its published locale variants. All enrichment (the per-image media lookup
  # + `srcset`, and the `translations` lookup for hreflang/locale links) happens
  # here at cache-miss time, so a cache *hit* carries resolved media URLs and
  # translations and issues no further DB queries. Returns `nil` (not cached)
  # when nothing is found.
  defp payload(fetch, locale, ct, org_id, audiences) do
    case localized(fetch, locale) do
      nil ->
        nil

      record ->
        %{
          record: record,
          blocks: blocks(record, org_id),
          translations: translations(ct, record.slug, org_id, audiences)
        }
    end
  end

  # Fetch the record in `locale`, falling back to the default locale's version.
  defp localized(fetch, locale) do
    default = I18n.default_locale()

    case fetch.(locale) do
      nil when locale != default -> fetch.(default)
      record -> record
    end
  end

  # Assign SEO metadata (read by the root layout) and the pre-enriched blocks,
  # then render. `payload` is a `%{record, blocks}` map (see `payload/2`) and
  # `ct` its `ContentTypes` entry.
  defp render_content(
         conn,
         template,
         %{record: record, blocks: blocks, translations: translations},
         ct,
         audiences
       ) do
    # A render that depended on WHO asked must never be shared-cached. The public
    # headers carry `public, max-age=60, stale-while-revalidate=300`, so a CDN in
    # front would happily serve one member's gated render to every anonymous
    # visitor. ETag/304 is skipped for the same reason — a conditional hit would
    # revalidate against a body that isn't the same for everyone.
    private? = audiences != []

    conn =
      if private?,
        do: put_private_delivery_headers(conn),
        else: put_delivery_cache_headers(conn, record)

    start = System.monotonic_time()

    result =
      if not private? and delivery_fresh?(conn, record) do
        send_resp(conn, :not_modified, "")
      else
        render_content_body(conn, template, record, blocks, translations, ct)
      end

    # Delivery-render duration telemetry (#206), tagged by content type and
    # whether the response was a 304.
    :telemetry.execute(
      [:kiln_cms, :delivery, :render],
      %{duration: System.monotonic_time() - start, count: 1},
      %{type: to_string(ct.type), status: result.status}
    )

    result
  end

  defp render_content_body(conn, template, record, blocks, translations, ct) do
    org = KilnCMSWeb.Tenant.current_org(conn)
    base_url = KilnCMSWeb.Tenant.base_url(org)

    conn
    |> assign(:locale, record.locale)
    |> assign(:page_title, record.seo_title || record.title)
    |> assign(:meta_description, record.seo_description)
    |> assign(:meta_keywords, record.seo_keywords)
    |> assign(
      :canonical_url,
      record.canonical_url || locale_url(ct, record.slug, record.locale, base_url)
    )
    |> assign(:og_image, record.seo_image)
    |> assign(:og_type, "article")
    |> assign(:hreflang, hreflang_alternates(ct, translations, base_url))
    |> assign(:locale_links, locale_links(ct, translations, record.locale, base_url))
    |> assign(:feeds, feed_alternates(ct, org, base_url))
    |> assign(:json_ld, json_ld_script(StructuredData.document(record, ct, org)))
    |> render(template, record: record, blocks: blocks)
  end

  # Feed autodiscovery (#486): the site-wide feed plus this type's own, so a
  # reader landing on a post can subscribe to just that type. Built from
  # `FeedController.feed_path/2` rather than spelled out here, so the advertised
  # URL and the routed one cannot drift. A type that doesn't syndicate
  # advertises only the site-wide feed; if nothing syndicates, nothing is
  # advertised at all.
  defp feed_alternates(ct, org, base_url) do
    site = KilnCMS.Branding.for_org(org.id).site_name

    scopes =
      if Feeds.syndicated?(ct) do
        [{nil, site}, {ct, "#{site} — #{ct.label}"}]
      else
        [{nil, site}]
      end

    if Feeds.syndicated_types(org.id) == [] do
      []
    else
      for {scope, title} <- scopes,
          {format, mime} <- [{:atom, "application/atom+xml"}, {:json, "application/feed+json"}] do
        %{
          type: mime,
          title: title,
          href: base_url <> KilnCMSWeb.FeedController.feed_path(scope, format)
        }
      end
    end
  end

  # Published locale variants of `slug`, scoped to the request's site (#336) so
  # hreflang/locale links never point at another org's content. Best-effort: a
  # content type without a translations interface simply yields none.
  defp translations(ct, slug, org_id, audiences) do
    ContentTypes.list_translations(ct.type, slug,
      audiences: audiences,
      authorize?: false,
      tenant: org_id
    )
  rescue
    _ -> []
  end

  # `rel="alternate" hreflang` entries for every published locale variant, plus
  # an `x-default` pointing at the default locale.
  defp hreflang_alternates(ct, translations, base_url) do
    default = I18n.default_locale()

    alternates =
      for t <- translations,
          do: %{hreflang: t.locale, href: locale_url(ct, t.slug, t.locale, base_url)}

    case Enum.find(translations, &(&1.locale == default)) do
      nil ->
        alternates

      t ->
        alternates ++
          [%{hreflang: "x-default", href: locale_url(ct, t.slug, default, base_url)}]
    end
  end

  # Language-switcher links to each published translation of this record.
  defp locale_links(ct, translations, current, base_url) do
    translations
    |> Enum.map(
      &%{
        locale: &1.locale,
        href: locale_url(ct, &1.slug, &1.locale, base_url),
        current: &1.locale == current
      }
    )
    |> Enum.sort_by(& &1.locale)
  end

  # Absolute public URL for `slug` in `locale` (non-default locales are prefixed).
  defp locale_url(ct, slug, locale, base_url) do
    prefix = if locale == I18n.default_locale(), do: "", else: "/#{locale}"
    "#{base_url}#{prefix}#{ContentTypes.public_prefix(ct)}/#{slug}"
  end

  # Pre-render the JSON-LD as a safe <script> tag. HEEx doesn't interpolate
  # inside a literal <script> element, so the layout injects this with `{...}`.
  # `escape: :html_safe` escapes `<`/`>`/`&`, so the JSON can't break out of the
  # tag.
  defp json_ld_script(data) do
    json = Jason.encode!(data, escape: :html_safe)
    Phoenix.HTML.raw(~s(<script type="application/ld+json">#{json}</script>))
  end

  defp blocks(record, org_id) do
    # Blocks are stored as the typed union (Kiln v2); convert back to legacy block
    # structs so the existing media-enriching renderer (`BlockComponents`) is
    # unchanged. A `columns` block (#335) nests child blocks, so the tree is built
    # recursively and flattened once for the media/form preloads — a nested image
    # or form is loaded in the same batched query as a top-level one.
    tree = block_tree(record.blocks)
    flat = flatten_block_tree(tree)

    media = load_block_media(flat, org_id)
    forms = load_block_forms(flat, org_id)
    Enum.map(tree, &enrich_block(&1, media, forms))
  end

  # Typed union → legacy `KilnCMS.CMS.Block` structs, recursing into `columns`
  # children so each nested block is itself a legacy struct the renderer handles.
  defp block_tree(blocks) do
    blocks
    |> KilnCMS.CMS.TypedBlocks.to_typed()
    |> KilnCMS.CMS.TypedBlocks.to_legacy()
    |> Enum.map(&struct(KilnCMS.CMS.Block, &1))
    |> Enum.map(&nest_columns/1)
  end

  defp nest_columns(%KilnCMS.CMS.Block{type: :columns, data: data} = block) do
    cols =
      for col <- data["columns"] || [] do
        %{"blocks" => col |> Map.get("blocks", []) |> block_tree()}
      end

    %{block | data: Map.put(data, "columns", cols)}
  end

  defp nest_columns(block), do: block

  # Depth-first block list, so the media/form preloads see nested blocks too.
  defp flatten_block_tree(blocks) do
    Enum.flat_map(blocks, fn
      %KilnCMS.CMS.Block{type: :columns, data: %{"columns" => cols}} = block ->
        [block | Enum.flat_map(cols, &flatten_block_tree(&1["blocks"] || []))]

      block ->
        [block]
    end)
  end

  # Batch-load the active forms referenced by form blocks (fields included),
  # keyed by slug — inactive/unknown slugs simply don't enrich.
  defp load_block_forms(blocks, org_id) do
    slugs =
      for b <- blocks,
          to_string(b.type) == "form",
          slug = b.data["form_slug"] || b.content,
          is_binary(slug) and slug != "",
          uniq: true,
          do: slug

    # Tenant-scoped so a page only embeds forms from its own site (#336).
    Map.new(slugs, &{&1, KilnCMS.Forms.get_active(&1, org_id)})
  end

  # Batch-load the media items referenced by image and gallery blocks (so we
  # render one query, not one per image).
  #
  # A gallery's ids live one level down, inside its `images` list, so collecting
  # only top-level `media_id` would leave every gallery image with no srcset, no
  # focal point and no intrinsic dimensions on the public site — a silent
  # degradation, since the stored url still renders (#482).
  defp load_block_media(blocks, org_id) do
    ids = blocks |> Enum.flat_map(&block_media_ids/1) |> Enum.uniq()

    case ids do
      [] ->
        %{}

      ids ->
        # Tenant-scoped so a page can only enrich media from its own site (#336);
        # `authorize?: false` is the delivery bypass, so the tenant is the guard.
        CMS.list_media_items!(
          authorize?: false,
          tenant: org_id,
          query: [filter: [id: [in: ids]]]
        )
        |> Map.new(&{&1.id, &1})
    end
  end

  # Filtered to real uuids once, here, rather than in each clause.
  #
  # A blank `media_id` is the normal state of an image pasted in by URL — but
  # `media_id` is a free-text block field, so an importer or an API caller can
  # put anything in it, and `id` is a uuid column: Ash rejects a non-uuid at
  # query build, which means `list_media_items!` *raises* and the published page
  # 500s for every visitor. `KilnCMS.Firing.References` has guarded this since
  # it was written; delivery never did, and a gallery multiplies the exposure
  # from one id per block to N.
  defp block_media_ids(%{type: type, data: data}) do
    type |> to_string() |> media_ids_for(data) |> Enum.filter(&valid_media_id?/1)
  end

  defp block_media_ids(_block), do: []

  defp media_ids_for("image", data), do: [data["media_id"]]

  defp media_ids_for("gallery", data) do
    data["images"] |> List.wrap() |> Enum.filter(&is_map/1) |> Enum.map(& &1["media_id"])
  end

  defp media_ids_for(_type, _data), do: []

  defp valid_media_id?(id) when is_binary(id), do: match?({:ok, _}, Ecto.UUID.cast(id))
  defp valid_media_id?(_id), do: false

  defp enrich_block(block, media, forms) do
    base = %{type: to_string(block.type), content: block.content}

    cond do
      block.type == :columns ->
        enrich_columns(base, block, media, forms)

      block.type == :image && match?(%{}, media[block.data["media_id"]]) ->
        item = media[block.data["media_id"]]

        Map.merge(base, %{
          srcset: srcset(item),
          # The block's own alt wins, with the library row as the fallback
          # behind it. This used to take `item.alt` unconditionally, which put
          # this surface at odds with every other one: the fired `:web`
          # artifact, the pop-out preview and the in-context editor all render
          # the block's alt, and `Validations.MediaAltText` gates publishing on
          # the block's alt and says in as many words that it "is what ships".
          # It wasn't. An image block described for its placement, pointing at a
          # library row nobody had filled in, passed the gate and then shipped
          # `alt=""` on the live site — the one surface the gate exists to
          # protect (#403, #482).
          alt: presence(block.data["alt"]) || item.alt,
          width: item.width,
          height: item.height,
          focal: focal_style(item)
        })

      block.type == :gallery ->
        enrich_gallery(base, block, media)

      block.type == :form ->
        # nil form (inactive/unknown slug) → the component renders nothing.
        Map.put(base, :form, forms[block.data["form_slug"] || block.content])

      true ->
        enrich_geo(base, block)
    end
  end

  # Per-item media enrichment (#482), mirroring what the `image` branch does for
  # a single image. An item whose `media_id` resolved to nothing still renders
  # from its stored url — just without srcset/focal/dimensions — which is what
  # happens when media is deleted out from under a published document.
  defp enrich_gallery(base, block, media) do
    images =
      for image <- block.data["images"] || [], is_map(image) do
        item = media[image["media_id"]]

        %{
          url: image["url"],
          # The item's own alt wins: it is the one written *for this placement*,
          # and `MediaItem.alt` is the library-wide default behind it. Same
          # precedence #403 established for the single-image block.
          alt: presence(image["alt"]) || (item && item.alt),
          caption: image["caption"],
          srcset: item && KilnCMS.Media.Presentation.srcset(item),
          width: item && item.width,
          height: item && item.height,
          focal: item && KilnCMS.Media.Presentation.focal_style(item)
        }
      end

    Map.merge(base, %{
      images: images,
      style: KilnCMS.Blocks.Gallery.layout_style(block.data["layout"])
    })
  end

  defp presence(value) when is_binary(value) do
    case String.trim(value) do
      "" -> nil
      trimmed -> trimmed
    end
  end

  defp presence(_value), do: nil

  # Embed cards (#489). Without these fields an embed reaches `BlockComponents`
  # as `%{type, content}` and the card branch — which needs a title — renders
  # nothing at all: the fired artifact and every preview showed a card while the
  # public page, the one surface that matters, showed an empty div.
  defp enrich_geo(base, %{type: :embed} = block) do
    Map.merge(base, %{
      title: block.data["title"],
      author_name: block.data["author_name"],
      provider_name: block.data["provider_name"],
      thumbnail_url: block.data["thumbnail_url"],
      resolved_url: block.data["resolved_url"]
    })
  end

  # GEO blocks (#357): surface the data-side fields the renderer reads.
  defp enrich_geo(base, %{type: :faq} = block),
    do: Map.put(base, :items, block.data["items"] || [])

  defp enrich_geo(base, %{type: :accordion} = block) do
    Map.merge(base, %{
      panels: block.data["panels"] || [],
      first_open: block.data["first_open"] == true
    })
  end

  defp enrich_geo(base, %{type: :how_to} = block) do
    Map.merge(base, %{description: block.data["description"], steps: block.data["steps"] || []})
  end

  defp enrich_geo(base, %{type: :claim} = block) do
    Map.merge(base, %{
      source_title: block.data["source_title"],
      source_url: block.data["source_url"]
    })
  end

  defp enrich_geo(base, _block), do: base

  # Recursively enrich a columns block's nested children (each column's blocks go
  # through the same `enrich_block/3` a top-level block does), and attach the grid
  # style so `BlockComponents` lays the container out identically to firing.
  defp enrich_columns(base, block, media, forms) do
    cols =
      for col <- block.data["columns"] || [] do
        %{blocks: Enum.map(col["blocks"] || [], &enrich_block(&1, media, forms))}
      end

    Map.merge(base, %{
      columns: cols,
      style:
        KilnCMS.Blocks.Columns.grid_style(block.data["layout"], block.data["gap"], length(cols))
    })
  end

  # `srcset/1` and `focal_style/1` live in `KilnCMS.Media.Presentation` — the
  # gallery block (#482) is the second consumer, and `srcset`'s exclusion of
  # cropped variants is the kind of rule that gets reintroduced by someone
  # writing a second builder rather than finding the first.
  defp srcset(item), do: KilnCMS.Media.Presentation.srcset(item)
  defp focal_style(item), do: KilnCMS.Media.Presentation.focal_style(item)

  defp not_found(conn) do
    conn
    # A 404 may be an unpublished/draft slug — never let a CDN or browser cache
    # it (it would mask the page once published).
    |> put_resp_header("cache-control", "no-store")
    |> put_status(:not_found)
    |> put_view(KilnCMSWeb.ErrorHTML)
    |> render(:"404")
  end

  # CDN/browser cache headers for published HTML: a short shared max-age with a
  # longer stale-while-revalidate window (the in-BEAM cache is single-node, so
  # these let a CDN absorb origin load), plus a content ETag for conditional GETs
  # and `Vary: Accept-Language` since delivery is locale-sensitive.
  # Personalised or paywalled HTML: never shared-cacheable. `Vary: Cookie` is a
  # belt (CDNs honour it unevenly); `no-store` is the actual control.
  defp put_private_delivery_headers(conn) do
    conn
    |> put_resp_header("cache-control", "private, no-store")
    |> put_resp_header("vary", "Cookie, Accept-Language")
  end

  defp put_delivery_cache_headers(conn, record) do
    conn
    |> put_resp_header("cache-control", "public, max-age=60, stale-while-revalidate=300")
    |> put_resp_header("vary", "Accept-Language")
    |> put_resp_header("etag", etag(record))
  end

  defp etag(record) do
    raw = "#{record.id}:#{record.updated_at}:#{record.published_version_id}"
    digest = :sha256 |> :crypto.hash(raw) |> Base.encode16(case: :lower) |> binary_part(0, 16)
    ~s("#{digest}")
  end

  defp delivery_fresh?(conn, record) do
    match?([_ | _], get_req_header(conn, "if-none-match")) and
      etag(record) in get_req_header(conn, "if-none-match")
  end
end
